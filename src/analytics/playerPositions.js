export function resolvePlayerPosition(name = "", currentPos = "", slot = "") {
  const p = (currentPos || "").toUpperCase().trim();
  if (p.includes("QB")) return "QB";
  if (p.includes("RB")) return "RB";
  if (p.includes("WR")) return "WR";
  if (p.includes("TE")) return "TE";
  if (p.includes("K")) return "K";
  if (p.includes("DEF") || p.includes("D/ST") || p.includes("DST")) return "DEF";

  const cleanName = (name || "").trim().toLowerCase();
  if (PLAYER_POSITION_MAP[cleanName]) {
    return PLAYER_POSITION_MAP[cleanName];
  }

  const s = (slot || "").toUpperCase().trim();
  if (s.includes("QB")) return "QB";
  if (s.includes("RB")) return "RB";
  if (s.includes("WR")) return "WR";
  if (s.includes("TE")) return "TE";
  if (s.includes("K")) return "K";
  if (s.includes("DEF") || s.includes("D/ST") || s.includes("DST")) return "DEF";

  return "FLEX";
}
